//go:embed contract/webapp.schema.json
var schemaBytes []byte
var schemaOnce sync.Once
var resolvedSchema *jsonschema.Resolved
var schemaErr error
var idPattern = regexp.MustCompile(`^webapp-[a-f0-9]{16}$`)
var opaquePattern = regexp.MustCompile(`^[a-f0-9]{48}$`)
var secretPattern = regexp.MustCompile(`(^|_)(password|passwd|secret|token|access_token|auth_token|bearer_token|refresh_token|api_key|model_key|client_secret|private_key)$`)
var camelBoundary = regexp.MustCompile(`([a-z0-9])([A-Z])`)

func strictJSON(raw []byte, target any) error {
	// encoding/json accepts duplicate keys, unlike a frozen review snapshot.
	var walk func(*json.Decoder) error
	walk = func(d *json.Decoder) error {
		t, err := d.Token()
		if err != nil {
			return err
		}
		if delim, ok := t.(json.Delim); ok {
			switch delim {
			case '{':
				seen := map[string]bool{}
				for d.More() {
					k, err := d.Token()
					if err != nil {
						return err
					}
					key, ok := k.(string)
					if !ok || seen[key] {
						return fmt.Errorf("duplicate JSON key")
					}
					seen[key] = true
					if err := walk(d); err != nil {
						return err
					}
				}
			case '[':
				for d.More() {
					if err := walk(d); err != nil {
						return err
					}
				}
			default:
				return fmt.Errorf("unexpected JSON delimiter")
			}
			_, err = d.Token()
			return err
		}
		return nil
	}
	d := json.NewDecoder(bytes.NewReader(raw))
	if err := walk(d); err != nil {
		return err
	}
	if _, err := d.Token(); err != io.EOF {
		return fmt.Errorf("trailing JSON")
	}
	var object any
	if err := json.Unmarshal(raw, &object); err != nil {
		return err
	}
	if err := exactKeys(object, reflect.TypeOf(target).Elem()); err != nil {
		return err
	}
	d = json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	return d.Decode(target)
}

func exactKeys(value any, typ reflect.Type) error {
	if typ == reflect.TypeOf(json.RawMessage{}) {
		return nil
	}
	if value == nil {
		if typ.Kind() == reflect.Pointer || typ.Kind() == reflect.Interface {
			return nil
		}
		return fmt.Errorf("unexpected JSON null")
	}
	for typ.Kind() == reflect.Pointer {
		typ = typ.Elem()
	}
	switch typ.Kind() {
	case reflect.Struct:
		object, ok := value.(map[string]any)
		if !ok {
			return nil
		}
		fields := map[string]reflect.Type{}
		for i := 0; i < typ.NumField(); i++ {
			f := typ.Field(i)
			fields[strings.Split(f.Tag.Get("json"), ",")[0]] = f.Type
		}
		for k, v := range object {
			field, ok := fields[k]
			if !ok {
				return fmt.Errorf("unknown JSON field")
			}
			if err := exactKeys(v, field); err != nil {
				return err
			}
		}
	case reflect.Slice:
		if items, ok := value.([]any); ok {
			for _, v := range items {
				if err := exactKeys(v, typ.Elem()); err != nil {
					return err
				}
			}
		}
	case reflect.Map:
		if values, ok := value.(map[string]any); ok {
			for _, v := range values {
				if err := exactKeys(v, typ.Elem()); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

// DecodeRequest shares managed records' exact JSON checks with HTTP adapters.
func DecodeRequest(raw []byte, target any) error {
	if strictJSON(raw, target) != nil {
		return fail("webapp_invalid_request", 400)
	}
	return nil
}

func ParseManifest(raw []byte) (Manifest, error) {
	var m Manifest
	bad := func() (Manifest, error) { return m, fail("webapp_manifest_invalid", 400) }
	if len(raw) > 256<<10 || strictJSON(raw, &m) != nil {
		return bad()
	}
	schemaOnce.Do(func() {
		// The one JS lookahead in health.path is lowered to an equivalent RE2
		// prefix assertion. All schema fields remain generated by Desktop.
		var object any
		if schemaErr = json.Unmarshal(schemaBytes, &object); schemaErr != nil {
			return
		}
		var lower func(any)
		lower = func(v any) {
			switch v := v.(type) {
			case map[string]any:
				// Zod's exported schema describes normalized output: properties
				// with defaults are required there, but optional on input.
				if props, ok := v["properties"].(map[string]any); ok {
					if required, ok := v["required"].([]any); ok {
						kept := []any{}
						for _, key := range required {
							prop, _ := props[key.(string)].(map[string]any)
							if _, hasDefault := prop["default"]; !hasDefault {
								kept = append(kept, key)
							}
						}
						v["required"] = kept
					}
				}
				for k, child := range v {
					if k == "pattern" && child == `^\/(?!\/)` {
						v[k] = `^/([^/]|$)`
					} else {
						lower(child)
					}
				}
			case []any:
				for _, child := range v {
					lower(child)
				}
			}
		}
		lower(object)
		b, _ := json.Marshal(object)
		var schema jsonschema.Schema
		if schemaErr = json.Unmarshal(b, &schema); schemaErr == nil {
			resolvedSchema, schemaErr = schema.Resolve(nil)
		}
	})
	if schemaErr != nil {
		return m, fmt.Errorf("load WebApp schema: %w", schemaErr)
	}
	var value any
	if json.Unmarshal(raw, &value) != nil || resolvedSchema.Validate(value) != nil {
		return bad()
	}
	if m.AppConfig == nil {
		m.AppConfig = map[string]any{}
	}
	if m.Frontend.RouteConfig.BackendPrefixes == nil {
		m.Frontend.RouteConfig.BackendPrefixes = []string{}
	}
	if len(m.Frontend.RouteConfig.BackendPrefixes) > 0 && m.Backend == nil {
		return bad()
	}
	paths := []string{m.Frontend.Root, m.Frontend.Index}
	if p := m.Frontend.RouteConfig.NavigationFallback; p != "" {
		paths = append(paths, p)
	}
	if b := m.Backend; b != nil {
		paths = append(paths, b.Command.Entry)
		if b.Health.StartupTimeoutMS == 0 {
			b.Health.StartupTimeoutMS = 10000
		}
		if b.ShutdownTimeoutMS == 0 {
			b.ShutdownTimeoutMS = 3000
		}
		if b.Args == nil {
			b.Args = []string{}
		}
		if b.Env == nil {
			b.Env = map[string]string{}
		}
		for k := range b.Env {
			if k == "HOST" || k == "PORT" || strings.HasPrefix(k, "WEBAPP_") || strings.HasPrefix(k, "DESKTOP_") {
				return bad()
			}
		}
		if b.Command.Type == "executable" && m.Target == "any" {
			return bad()
		}
		if b.Command.Type == "runtime" && ((b.Command.Runtime == "python" && strings.ToLower(path.Ext(b.Command.Entry)) != ".py") || (b.Command.Runtime == "java" && strings.ToLower(path.Ext(b.Command.Entry)) != ".jar")) {
			return bad()
		}
	}
	for _, p := range paths {
		if !safeRelative(p) {
			return bad()
		}
	}
	seen := map[string]bool{}
	for _, p := range m.Frontend.RouteConfig.BackendPrefixes {
		if seen[p] || !strings.HasPrefix(p, "/") || p == "/" || strings.HasSuffix(p, "/") || strings.ContainsAny(p, "?#\\\x00") || p == "/__desktop" || strings.HasPrefix(p, "/__desktop/") || strings.Contains(p, "//") || path.Clean(p) != p {
			return bad()
		}
		seen[p] = true
	}
	if unsafeJSON(m.AppConfig) {
		return bad()
	}
	if b, _ := json.Marshal(m.AppConfig); len(b) > 128<<10 {
		return bad()
	}
	if m.UserConfig != nil {
		seen = map[string]bool{}
		for i := range m.UserConfig.Fields {
			f := &m.UserConfig.Fields[i]
			if seen[f.Name] || unsafeKey(f.Name) || m.Copilot != nil && f.Name == "agentKey" {
				return bad()
			}
			seen[f.Name] = true
			if f.Type == "text" && f.MaxLength == 0 {
				f.MaxLength = 1024
			}
			if f.Type == "textarea" && f.MaxLength == 0 {
				f.MaxLength = 8000
			}
			if f.Type == "text" || f.Type == "textarea" {
				if v, ok := f.Default.(string); ok && len(utf16.Encode([]rune(v))) > f.MaxLength {
					return bad()
				}
			}
			if f.Type == "number" {
				if f.Min != nil && f.Max != nil && *f.Min > *f.Max {
					return bad()
				}
				if v, ok := f.Default.(float64); ok && (f.Min != nil && v < *f.Min || f.Max != nil && v > *f.Max) {
					return bad()
				}
			}
			if f.Type == "select" && f.Source == "" {
				values := map[string]bool{}
				for _, o := range f.Options {
					if values[o.Value] {
						return bad()
					}
					values[o.Value] = true
				}
				if v, ok := f.Default.(string); ok && !values[v] {
					return bad()
				}
			}
		}
		if b, _ := json.Marshal(m.UserConfig); len(b) > 64<<10 {
			return bad()
		}
	}
	if m.Copilot != nil {
		seen = map[string]bool{}
		for _, r := range m.Copilot.References {
			if seen[strings.ToLower(r.ID)] {
				return bad()
			}
			seen[strings.ToLower(r.ID)] = true
		}
	}
	m.Label = strings.TrimSpace(m.Label)
	if m.Label == "" {
		return bad()
	}
	canonical, err := json.Marshal(m)
	if err != nil || len(canonical) > 256<<10 {
		return bad()
	}
	return m, nil
}

func safeRelative(p string) bool {
	return p != "" && !strings.ContainsAny(p, "\\:\x00") && !strings.HasPrefix(p, "/") && path.Clean(p) == p && p != "." && p != ".." && !strings.HasPrefix(p, "../")
}
func unsafeKey(k string) bool {
	n := strings.ToLower(strings.ReplaceAll(camelBoundary.ReplaceAllString(k, "${1}_${2}"), "-", "_"))
	return k == "__proto__" || k == "prototype" || k == "constructor" || secretPattern.MatchString(n)
}
func unsafeJSON(v any) bool {
	switch v := v.(type) {
	case map[string]any:
		for k, c := range v {
			if unsafeKey(k) || unsafeJSON(c) {
				return true
			}
		}
	case []any:
		for _, c := range v {
			if unsafeJSON(c) {
				return true
			}
		}
	}
	return false
}

func validateCompose(m Manifest) error {
	if m.Target != "any" && m.Target != "linux-x64" {
		return fail("webapp_target_unsupported", 400)
	}
	if m.Backend != nil {
		if m.Backend.Command.Type != "electron-node" {
			return fail("webapp_launcher_unsupported", 400)
		}
		if e := strings.ToLower(path.Ext(m.Backend.Command.Entry)); e != ".js" && e != ".mjs" && e != ".cjs" {
			return fail("webapp_backend_entry_invalid", 400)
		}
		for k := range m.Backend.Env {
			if k == "NODE_OPTIONS" || k == "NODE_PATH" || k == "HOME" || k == "TMPDIR" || k == "PATH" || strings.HasPrefix(k, "LD_") || strings.HasPrefix(k, "DYLD_") || strings.HasPrefix(k, "AP_") {
				return fail("webapp_backend_env_forbidden", 400)
			}
		}
	}
	return nil
}
